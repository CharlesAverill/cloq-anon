"""Write funcs.h: the exact bytes of each analyzed function, taken from the
binaries the proofs were lifted from (../<dir>/<binary>), and each function's
offset within its 4 KiB page, so the harness can run the same bytes at the same
alignment.

    python3 extract.py > funcs.h
"""
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
FUNCS = [  # (C name in the harness, binary, symbol)
    ('sum', 'cache/cache', 'sum'),
    ('while_true_break', 'while_true_break/while_true_break', 'while_true_break'),
    ('find', 'arraysearch/arraysearch', 'find'),
    ('collatz', 'collatz/collatz', 'collatz'),
    ('find_in_list', 'llsearch/linked_list', 'find_in_list'),
    ('insert_after_pos_in_list', 'llsearch/linked_list', 'insert_after_pos_in_list'),
    ('insert_in_sorted_list', 'llsearch/linked_list', 'insert_in_sorted_list'),
]


def func(binary, sym):
    out = subprocess.run(['objdump', '-d', f'--disassemble={sym}', binary], check=True,
                         capture_output=True, text=True).stdout
    addr, data, inside = None, bytearray(), False
    for line in out.splitlines():
        if line.endswith(f'<{sym}>:'):
            addr, inside = int(line.split()[0], 16), True
        elif inside and line.strip() and ':' in line and '\t' in line:
            data += bytes.fromhex(line.split('\t')[1].replace(' ', ''))
    assert addr is not None and data, (binary, sym)
    return addr, bytes(data)


print('/* Generated by extract.py from the analyzed binaries; do not edit. */')
for name, binary, sym in FUNCS:
    addr, data = func(str(HERE.parent / binary), sym)
    body = ', '.join(f'0x{b:02x}' for b in data)
    print(f'/* {sym} at 0x{addr:x} in {binary} */')
    print(f'static const unsigned char code_{name}[] = {{ {body} }};')
    print(f'#define PAGEOFF_{name} 0x{addr % 4096:x}')
